import * as NodeFS from "node:fs";
import { areaOf, isIgnoredPath } from "./t3team-placement-areas.mjs";

// The Nexi footprint of the fork = what differs from upstream, measured against the upstream
// commit this branch is based on (merge-base HEAD upstream/main), NOT against live upstream.
//   - a file upstream does not have            -> kind "file",     loc = non-empty lines
//   - an upstream file this fork has modified  -> kind "modified", loc = lines ADDED vs upstream
// Measuring the diff (instead of "t3team-" prefixes) means an upstream sync cannot change it: the
// sync moves the merge-base along with the tree. Only a file the fork itself adds or edits counts.

export function parseNameStatus(text) {
  const status = new Map();
  for (const line of text.split("\n")) {
    const [code, ...rest] = line.split("\t");
    if (!code || rest.length === 0) continue;
    status.set(rest[rest.length - 1], code[0]);
  }
  return status;
}

/** `git diff --numstat` lines: "<added>\t<deleted>\t<path>"; binary files report "-". */
export function parseNumstat(text) {
  const rows = new Map();
  for (const line of text.split("\n")) {
    const [added, , ...rest] = line.split("\t");
    if (rest.length === 0) continue;
    rows.set(rest.join("\t"), added === "-" ? 0 : Number(added));
  }
  return rows;
}

export function countNonEmptyLinesOf(text) {
  if (text.includes("\u0000")) return 0;
  return text.split(/\r?\n/).filter((line) => line.trim().length > 0).length;
}

function readLocOf(cwd, filePath) {
  try {
    return countNonEmptyLinesOf(NodeFS.readFileSync(`${cwd}/${filePath}`, "utf8"));
  } catch {
    return null;
  }
}

/**
 * Collects footprint items ({ path, area, kind, loc }) for the working tree.
 * `git` is injected (args => stdout) so tests do not need a repository; `pathspecs` narrows the
 * diff (restricted areas only) when the full report is not needed.
 */
export function collectFootprint({ cwd, git, mergeBase, extraIgnoreGlobs = [], pathspecs = [] }) {
  const base = ["-c", "core.quotepath=false", "diff", "--no-renames", "--diff-filter=AM"];
  const tail = [mergeBase, "--", ...pathspecs];
  const status = parseNameStatus(git([...base, "--name-status", ...tail]));
  const added = parseNumstat(git([...base, "--numstat", ...tail]));
  const untracked = git(["ls-files", "--others", "--exclude-standard", "--", ...pathspecs]);
  for (const filePath of untracked.split("\n").filter(Boolean)) status.set(filePath, "A");

  const items = new Map();
  for (const [filePath, code] of status) {
    if (isIgnoredPath(filePath, extraIgnoreGlobs)) continue;
    const kind = code === "A" ? "file" : "modified";
    const loc = kind === "file" ? readLocOf(cwd, filePath) : (added.get(filePath) ?? 0);
    if (loc === null) continue; // listed by git but gone from disk (deleted after staging)
    if (kind === "modified" && loc === 0) continue; // deletions-only edit adds no footprint
    items.set(filePath, { path: filePath, area: areaOf(filePath), kind, loc });
  }
  return items;
}

export const BASELINE_FILE = ".t3team-placement-baseline.jsonl";

const BASELINE_HEADER = {
  version: 1,
  rule: "Nexi footprint in the fork's restricted areas. GENERATED by `node t3team-additive-guard.mjs --write-placement-baseline`; never edit by hand. It may only shrink.",
};

/** One JSON object per line, sorted by path, so concurrent edits to different files merge cleanly. */
export function serializeBaseline(items) {
  const lines = [JSON.stringify(BASELINE_HEADER)];
  for (const item of [...items].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))) {
    lines.push(JSON.stringify({ p: item.path, a: item.area, k: item.kind, l: item.loc }));
  }
  return `${lines.join("\n")}\n`;
}

/** Returns { entries: Map<path, {area, kind, loc}>, errors: string[] }; never throws. */
export function parseBaseline(text) {
  const entries = new Map();
  const errors = [];
  if (/^(<<<<<<<|=======|>>>>>>>)/m.test(text)) {
    errors.push(`${BASELINE_FILE} has merge-conflict markers`);
    return { entries, errors };
  }
  const lines = text.split("\n").filter((line) => line.trim().length > 0);
  lines.forEach((line, index) => {
    try {
      const row = JSON.parse(line);
      if (index === 0 && row.version !== undefined) return;
      if (typeof row.p !== "string" || typeof row.l !== "number") throw new Error("bad entry");
      if (entries.has(row.p)) errors.push(`${BASELINE_FILE} lists ${row.p} twice`);
      entries.set(row.p, { area: row.a, kind: row.k, loc: row.l });
    } catch {
      errors.push(`${BASELINE_FILE} line ${index + 1} is not a valid entry`);
    }
  });
  return { entries, errors };
}
